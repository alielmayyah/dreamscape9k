import os
import json
import re
import shutil
from PIL import Image

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
PUBLIC_ART = os.path.join(BASE_DIR, "public", "images", "artwork")
PUBLIC_THUMB = os.path.join(BASE_DIR, "public", "images", "thumbs")
DATA_FILE = os.path.join(BASE_DIR, "src", "data", "artworks.ts")

os.makedirs(PUBLIC_ART, exist_ok=True)
os.makedirs(PUBLIC_THUMB, exist_ok=True)

# 1. Sync all root image files to public/images/artwork
root_files = [f for f in os.listdir(BASE_DIR) if os.path.isfile(f) and f.lower().endswith(('.jpg', '.jpeg', '.png', '.webp'))]
print(f"Total root files found: {len(root_files)}")

for f in root_files:
    clean = re.sub(r'[^\w\.-]', '_', f)
    dst_art = os.path.join(PUBLIC_ART, clean)
    shutil.copy2(f, dst_art)
    
    thumb_name = os.path.splitext(clean)[0] + ".webp"
    dst_thumb = os.path.join(PUBLIC_THUMB, thumb_name)
    if not os.path.exists(dst_thumb):
        with Image.open(dst_art) as img:
            img = img.convert("RGB")
            img.thumbnail((800, 800), Image.Resampling.LANCZOS)
            img.save(dst_thumb, "WEBP", quality=82)

